// Fetches everything the dashboard needs and derives the view-model.

import { useCallback, useEffect, useRef, useState } from "react";
import { api, GarminSyncError, type GarminFailure } from "./api";
import { TREND_DAYS, buildViewModel, isParticipating, isPastEvent, localISO, movePlanSession, visibleEvents, type ViewModel } from "./derive";
import type { RaceEvent, Plan, PlanRequest, RecoveryRow, SeasonPlan, SyncStatus, Vo2maxRow, Weather, WorkoutRow } from "./types";

// Asked before a sync or re-plan while the athlete has plan changes in force:
// keep them in the new plan, or overwrite them with a fresh one.
export interface PlanRequestPrompt {
  action: "sync" | "replan";
  requests: PlanRequest[];
}

export interface DashboardState {
  loading: boolean;
  error: string | null;
  vm: ViewModel | null;
  workouts: WorkoutRow[];
  events: RaceEvent[];
  primaryEvent: RaceEvent | null;
  weather: Weather | null;
  status: SyncStatus | null;
  plan: Plan | null;
  // The persistent week-by-week season plan; null when the athlete has none.
  seasonPlan: SeasonPlan | null;
  syncing: boolean;
  // True while the backend is waiting for the Garmin MFA email code.
  mfaPending: boolean;
  // Pipeline step of the running sync (drives the Sync button's live label).
  syncPhase: string | null;
  syncError: string | null;
  // A sync that failed on Garmin's Personal API (expired key, Garmin down):
  // App shows GarminErrorModal with the suggested action until dismissed.
  garminFailure: GarminFailure | null;
  clearGarminFailure: () => void;
  // Informational note about the last sync (e.g. plan regeneration skipped
  // because nothing new was synced). Auto-clears after a few seconds.
  syncNotice: string | null;
  // Put a line in the green notice strip (the season plan following new
  // coach instructions).
  showNotice: (text: string) => void;
  // Fresh plan generated by the AI coach during the last sync — App shows it as
  // a summary popup until dismissed.
  coachSummary: Plan | null;
  clearCoachSummary: () => void;
  refresh: () => void;
  // A planned session dragged to another day: shown at once, saved behind it.
  // Rejects with the backend's reason after putting the plan back.
  moveSession: (fromDate: string, sessionIndex: number, toDate: string) => Promise<void>;
  // The Sync Garmin and Re-sync plan buttons. Each first checks for plan
  // changes the athlete asked the coach for, and asks about them if any.
  startSync: () => Promise<void>;
  // True while the coach is regenerating the plan on demand (no Garmin sync).
  replanning: boolean;
  startReplan: () => Promise<void>;
  // Open while the athlete is being asked about their plan changes.
  planRequestPrompt: PlanRequestPrompt | null;
  // null cancels: nothing runs.
  answerPlanRequestPrompt: (choice: "keep" | "overwrite" | null) => void;
}

// The nearest upcoming event; with none, the most recently finished one still
// shown in the events row. Chosen from visibleEvents so a hidden event never
// comes back as the primary, and only from events the athlete is racing: a
// calendar-only event is never the goal (same rule as active_event).
function primaryOf(events: RaceEvent[]): RaceEvent | null {
  const shown = visibleEvents(events).filter(isParticipating);
  const today = localISO(new Date());
  const upcoming = shown
    .filter((g) => (g.race_date || "") >= today)
    .sort((a, b) => a.race_date.localeCompare(b.race_date));
  if (upcoming[0]) return upcoming[0];
  const past = shown.filter((g) => isPastEvent(g)).sort((a, b) => b.race_date.localeCompare(a.race_date));
  return past[0] ?? null;
}

export function useDashboardData(): DashboardState {
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [vm, setVm] = useState<ViewModel | null>(null);
  const [workouts, setWorkouts] = useState<WorkoutRow[]>([]);
  const [events, setEvents] = useState<RaceEvent[]>([]);
  const [primaryEvent, setPrimaryEvent] = useState<RaceEvent | null>(null);
  const [weather, setWeather] = useState<Weather | null>(null);
  const [status, setStatus] = useState<SyncStatus | null>(null);
  const [plan, setPlan] = useState<Plan | null>(null);
  const [seasonPlan, setSeasonPlan] = useState<SeasonPlan | null>(null);
  const [syncing, setSyncing] = useState(false);
  const [replanning, setReplanning] = useState(false);
  const [mfaPending, setMfaPending] = useState(false);
  const [syncPhase, setSyncPhase] = useState<string | null>(null);
  const [syncError, setSyncError] = useState<string | null>(null);
  const [garminFailure, setGarminFailure] = useState<GarminFailure | null>(null);
  const [syncNotice, setSyncNotice] = useState<string | null>(null);
  const [coachSummary, setCoachSummary] = useState<Plan | null>(null);
  const [planRequestPrompt, setPlanRequestPrompt] = useState<PlanRequestPrompt | null>(null);
  // The open prompt, mirrored in a ref: an answer takes it from here, so a
  // second answer in the same tick (a double key event) finds it gone instead
  // of reading the stale state and starting a second paid run.
  const promptRef = useRef<PlanRequestPrompt | null>(null);
  // Set from the click until the run starts or the prompt is answered, so a
  // second click cannot start a second check (state would lag a render).
  const gateBusy = useRef(false);
  const [tick, setTick] = useState(0);

  const refresh = useCallback(() => setTick((t) => t + 1), []);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    (async () => {
      try {
        const [load, workouts, eventList, st, rec, vo2max, recovery, season] = await Promise.all([
          api.load(TREND_DAYS, "all"),
          // 60 days: the Training Days grid spans two months. Every other
          // consumer windows its own range (7-day HR zones, 8-week charts
          // needing 55 days, the 28-day discipline cards), so the extra rows
          // are inert there.
          api.workouts(60),
          api.events().catch(() => [] as RaceEvent[]),
          api.syncStatus().catch(() => null),
          api.recommendation(),
          // Optional panel data: this Promise.all sits inside the try that sets
          // `error`, so an unavailable VO2max endpoint would otherwise blank the
          // whole dashboard. Same idiom as api.events() above.
          api.vo2max(TREND_DAYS).catch(() => [] as Vo2maxRow[]),
          api.recovery(56).catch(() => [] as RecoveryRow[]),
          api.seasonPlan(),
        ]);
        if (cancelled) return;
        setVm(buildViewModel(load, workouts, vo2max, recovery));
        setWorkouts(workouts);
        setEvents(eventList);
        setStatus(st);
        // A page reload can land while the backend is still waiting for an MFA
        // code from an earlier sync — resurface the prompt.
        if (st?.mfa_pending) setMfaPending(true);
        setPlan(rec);
        setSeasonPlan(season);
        const primary = primaryOf(eventList);
        setPrimaryEvent(primary);
        setError(null);
        if (primary) {
          api
            .weather(primary.event_id)
            .then((w) => !cancelled && setWeather(w))
            .catch(() => !cancelled && setWeather(null));
        } else {
          setWeather(null);
        }
      } catch (e) {
        if (!cancelled) setError(e instanceof Error ? e.message : String(e));
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [tick]);

  // Weather once a day: the backend looks it up at most once per event per
  // day, and a tab left open fetches it again a minute after local midnight,
  // so the chip moves to the new day's forecast without a reload.
  const weatherEventId = primaryEvent?.event_id ?? null;
  useEffect(() => {
    if (!weatherEventId) return;
    let timer = 0;
    let cancelled = false;
    const schedule = () => {
      const now = new Date();
      const next = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1, 0, 1);
      timer = window.setTimeout(() => {
        api
          .weather(weatherEventId)
          .then((w) => !cancelled && setWeather(w))
          .catch(() => {});
        schedule();
      }, next.getTime() - now.getTime());
    };
    schedule();
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
    };
  }, [weatherEventId]);

  // Page-reload case: MFA was flagged by the initial status fetch but no sync
  // request is running in this tab — keep polling so the prompt clears (or the
  // code submitted here is acknowledged) once the backend finishes.
  useEffect(() => {
    if (!mfaPending || syncing) return;
    const poll = window.setInterval(() => {
      api
        .syncStatus()
        .then((st) => {
          setStatus(st);
          if (!st.mfa_pending) setMfaPending(false);
        })
        .catch(() => {});
    }, 2000);
    return () => window.clearInterval(poll);
  }, [mfaPending, syncing]);

  // The notice is transient feedback, not state to keep around.
  useEffect(() => {
    if (!syncNotice) return;
    const t = window.setTimeout(() => setSyncNotice(null), 8000);
    return () => window.clearTimeout(t);
  }, [syncNotice]);

  // keepRequests is the athlete's answer about their plan changes; undefined
  // when there were none to ask about.
  const runSync = useCallback(async (keepRequests?: boolean) => {
    setSyncing(true);
    setSyncError(null);
    setGarminFailure(null);
    setSyncNotice(null);
    // The sync request blocks server-side (possibly minutes, waiting on Garmin
    // MFA), so poll the status endpoint to learn when a code is being asked for.
    const poll = window.setInterval(() => {
      api
        .syncStatus()
        .then((st) => {
          setStatus(st);
          setMfaPending(!!st.mfa_pending);
          setSyncPhase(st.sync_phase ?? null);
        })
        .catch(() => {});
    }, 2000);
    try {
      const result = await api.sync(keepRequests);
      refresh();
      // Pop the coach's summary only when this sync actually generated a plan.
      if (result.recommendation === "generated") {
        const rec = await api.recommendation();
        if (rec?.summary) setCoachSummary(rec);
      } else if (result.recommendation === "skipped (no new activities)") {
        setSyncNotice("Sync complete — no new activities, so the coach plan is unchanged.");
      }
      // A season-plan adjustment says more than "unchanged", so it wins the strip.
      if (result.season_plan_notice) setSyncNotice(result.season_plan_notice);
      // A lighter week is the athlete's to act on, so it wins the strip.
      if (result.load_reduction_notice) setSyncNotice(result.load_reduction_notice);
    } catch (e) {
      if (e instanceof GarminSyncError) setGarminFailure(e.failure);
      else setSyncError(`Sync failed: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      window.clearInterval(poll);
      setMfaPending(false);
      setSyncPhase(null);
      setSyncing(false);
    }
  }, [refresh]);

  // Regenerate the plan on demand (POST /recommend/trigger) — same completion
  // flow as a plan-producing sync: refresh + the coach-summary popup.
  const runReplan = useCallback(async (keepRequests?: boolean) => {
    setReplanning(true);
    setSyncError(null);
    setSyncNotice(null);
    try {
      const rec = await api.regeneratePlan(keepRequests);
      refresh();
      if (rec?.summary) setCoachSummary(rec);
      if (rec?.load_reduction?.message) setSyncNotice(rec.load_reduction.message);
    } catch (e) {
      setSyncError(`Plan regeneration failed: ${e instanceof Error ? e.message : String(e)}`);
    } finally {
      setReplanning(false);
    }
  }, [refresh]);

  // Both buttons go through here: with plan changes in force the athlete is
  // asked first (planRequestPrompt), otherwise the run starts straight away,
  // exactly as before this check existed.
  const start = useCallback(
    async (action: "sync" | "replan") => {
      if (gateBusy.current) return;
      gateBusy.current = true;
      const requests = await api.planRequests();
      if (requests.length) {
        promptRef.current = { action, requests };
        setPlanRequestPrompt(promptRef.current);
        return; // gateBusy stays set until the prompt is answered
      }
      gateBusy.current = false;
      await (action === "sync" ? runSync() : runReplan());
    },
    [runSync, runReplan],
  );
  const startSync = useCallback(() => start("sync"), [start]);
  const startReplan = useCallback(() => start("replan"), [start]);

  const answerPlanRequestPrompt = useCallback(
    (choice: "keep" | "overwrite" | null) => {
      const prompt = promptRef.current;
      if (!prompt) return; // already answered
      promptRef.current = null;
      setPlanRequestPrompt(null);
      gateBusy.current = false;
      if (choice === null) return;
      const keep = choice === "keep";
      void (prompt.action === "sync" ? runSync(keep) : runReplan(keep));
    },
    [runSync, runReplan],
  );

  const clearCoachSummary = useCallback(() => setCoachSummary(null), []);

  // No refresh(): only the plan changed, and everything reading it (the week's
  // totals, the Load Forecast) follows this state.
  const moveSession = useCallback(
    async (fromDate: string, sessionIndex: number, toDate: string) => {
      const before = plan;
      if (!before) return;
      setPlan(movePlanSession(before, fromDate, sessionIndex, toDate));
      try {
        setPlan(await api.moveSession(fromDate, sessionIndex, toDate));
      } catch (e) {
        setPlan(before);
        throw e;
      }
    },
    [plan],
  );

  // A line for the green notice strip from outside a sync (the season plan
  // following new coach instructions).
  const showNotice = useCallback((text: string) => setSyncNotice(text), []);

  const clearGarminFailure = useCallback(() => setGarminFailure(null), []);

  return { loading, error, vm, workouts, events, primaryEvent, weather, status, plan, seasonPlan, syncing, mfaPending, syncPhase, syncError, garminFailure, clearGarminFailure, syncNotice, showNotice, coachSummary, clearCoachSummary, refresh, moveSession, startSync, replanning, startReplan, planRequestPrompt, answerPlanRequestPrompt };
}
