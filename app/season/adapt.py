"""
Event-plan adaptation on every sync: reconcile() moves the plan's future
targets to what the athlete actually did and how fatigued they are. Pure and
idempotent -- the same inputs give the same plan and no new revision -- so it
is table-testable (tests/test_season_adapt.py) and safe to run on every sync,
including the ones that pulled nothing new (TSB moves on rest days).

Runs only from the sync and POST /recommend/trigger, never on a GET: it
changes the plan, and the plan only changes on a data refresh or the athlete's
own edit.

Rules, in order, on unpinned weeks that are not past, taper or race:
1. Fatigue gate (Friel zones). TSB below -40: the rest of this week is halved
   and becomes a recovery week, and next week is a recovery week. TSB -40 to
   -30: the next loading week after this one drops 20%.
2. Under-delivery. The last two completed loading weeks each came in under 80%
   of target (and neither was empty -- an empty week is a layoff, rule 5): the
   path is rebuilt from their mean, from this week on, at the same growth. No
   catch-up. A peak it can no longer reach is lowered.
3. Over-delivery hold. Last week over 115% of target with TSB below -10: this
   week is held at last week's target, no increase.
4. Fresh bonus. TSB +10 or more after a week at 95% of target or more: this
   week up 5%, never past the 10% cap over the last loading week.
5. Layoff. Seven days or more with no training: next week is a return week at
   60% of the last loading week, and the path regrows from there.

Rules 2-4 read the week just completed and act on THIS week: the first sync
of a week is the first moment the completed week is known, and the 7-day plan
regenerated by that sync is the one that carries the change.

Each rule fires once per trigger, recorded in the plan's `adapt_marks` (e.g.
"FATIGUE_GATE:2026-11-09"), so a second sync with the same data finds nothing
left to do. After a change the later unpinned weeks re-flow, so the 10% cap,
the 3 + 1 cadence and the taper still hold; the taper itself is never touched.
"""

from __future__ import annotations

import copy
from datetime import date, timedelta

from app.metrics.calculator import _step
from app.season import config as cfg
from app.season import split
from app.season.builder import cadence, eases_into_sub, resets_recovery

EDITABLE_KINDS = ("loading", "recovery", "return")


def _ws(w: dict) -> date:
    return date.fromisoformat(w["week_start"])


def current_index(weeks: list[dict], today: date) -> int | None:
    """The week containing today, or None (plan not started, or finished)."""
    for i, w in enumerate(weeks):
        if _ws(w) <= today <= _ws(w) + timedelta(days=6):
            return i
    return None


def _taper_start(weeks: list[dict]) -> int:
    return next((i for i, w in enumerate(weeks) if w["kind"] in ("taper", "race")), len(weeks))


def _editable(w: dict) -> bool:
    """A week the sync rules may change: unpinned, not the taper, and not a sub
    event's week (reflow re-sizes those, nothing turns them into another kind)."""
    return not w.get("pinned") and not w.get("sub_event") and w["kind"] in EDITABLE_KINDS


def _streak_before(weeks: list[dict], start: int) -> tuple[float | None, int]:
    """The last loading target and the loading weeks since a recovery, before `start`."""
    last, since = None, 0
    for w in weeks[:start]:
        if w["kind"] == "loading":
            last, since = w["target_tss"], since + 1
        elif w["kind"] == "return":
            last, since = w["target_tss"], 0
        elif resets_recovery(w):
            since = 0
    return last, since


def _set(w: dict, kind: str, tss: float, tss_per_hour: float, source: str = "adapt") -> None:
    tss = round(tss)
    if w["kind"] == kind and w["target_tss"] == tss:
        return
    w["kind"] = kind
    w["target_tss"] = tss
    w["target_hours"] = round(tss / tss_per_hour, 1)
    w["focus"] = cfg.FOCUS_TEXT.get(kind if kind in ("recovery", "return") else w["phase"])
    w["source"] = source


def reflow(plan: dict, start: int, level: float | None = None, fixed: frozenset[int] = frozenset()) -> None:
    """
    Re-walk the unpinned weeks from `start` to the taper with the builder's
    rules: grow the last loading week by the plan's growth up to the peak, a
    recovery week after every 3 loading weeks (not right before the taper).
    Pinned weeks and `fixed` ones keep their target and count as they stand.
    `level` is the first loading week's target when there is no loading week
    before `start` to grow from (an under-delivery re-anchor).
    """
    weeks = plan["weeks"]
    settings = plan.get("settings") or {}
    baseline = plan.get("baseline") or {}
    tss_per_hour = float(baseline.get("tss_per_hour") or cfg.DEFAULT_TSS_PER_HOUR)
    growth = min((settings.get("growth_pct_per_week") or 0) / 100, cfg.MAX_WEEKLY_GROWTH)
    ceiling = (plan.get("targets") or {}).get("peak_weekly_tss") or float("inf")
    cap = settings.get("weekly_hours_cap")
    cap_tss = round(cap * tss_per_hour) if cap else None
    taper_start = _taper_start(weeks)
    every = cadence(plan)

    last, since = _streak_before(weeks, start)
    if level is not None:
        last = None
    for i in range(start, taper_start):
        w = weeks[i]
        if w.get("sub_event") and not w.get("pinned") and i not in fixed:
            # A sub event's week follows the path: its share of the last
            # loading week, whatever that now is.
            factor = w.get("sub_factor") or 1.0
            base = last if last is not None else (level if level is not None else w["target_tss"] / factor)
            tss = round(base * factor)
            if tss != w["target_tss"]:
                w["target_tss"], w["target_hours"] = tss, round(tss / tss_per_hour, 1)
                w["source"] = "adapt"
            if resets_recovery(w):
                since = 0
            continue
        if w.get("pinned") or i in fixed or w["kind"] not in EDITABLE_KINDS:
            if w["kind"] == "loading":
                last, since = w["target_tss"], since + 1
            elif w["kind"] == "return":
                last, since = w["target_tss"], 0
            elif resets_recovery(w):
                since = 0
            continue
        before_sub = i + 1 < len(weeks) and eases_into_sub(weeks[i + 1])
        if since >= every and taper_start - i > 1 and last is not None and not before_sub:
            _set(w, "recovery", last * cfg.RECOVERY_FACTOR, tss_per_hour)
            since = 0
            continue
        if last is None:
            target = level if level is not None else w["target_tss"]
        else:
            target = min(round(last * (1 + growth)), max(ceiling, last))
        if cap_tss is not None:
            target = min(target, cap_tss)
        _set(w, "loading", target, tss_per_hour)
        last, since = round(target), since + 1


def retaper(plan: dict, today: date, only_if_above: bool = False) -> bool:
    """
    Size the taper and race weeks off the plan's highest loading week again,
    with the builder's factors. The sync rules leave the taper alone, but when
    the peak itself drops (a lower hours cap, an under-delivery re-anchor) a
    taper sized off the old peak would sit ABOVE the build. `only_if_above`
    limits it to that case. Weeks already over are left as they were. Returns
    True when a target moved.
    """
    weeks = plan["weeks"]
    taper_start = _taper_start(weeks)
    loading = [w["target_tss"] for w in weeks[:taper_start] if w["kind"] == "loading"]
    if not loading or taper_start == len(weeks):
        return False
    top = max(loading)
    if only_if_above and weeks[taper_start]["target_tss"] < top:
        return False
    event_type = (plan.get("event") or {}).get("type")
    row = cfg.PHASE_WEEKS_OUT.get(event_type) or cfg.PHASE_WEEKS_OUT[cfg.DEFAULT_EVENT_TYPE]
    factors = cfg.TAPER_FACTORS[row["taper"]]
    factors = factors[len(factors) - (len(weeks) - taper_start):]
    tph = float((plan.get("baseline") or {}).get("tss_per_hour") or cfg.DEFAULT_TSS_PER_HOUR)
    moved = False
    for f, w in zip(factors, weeks[taper_start:]):
        if _ws(w) + timedelta(days=6) < today or w.get("pinned"):
            continue
        target = round(top * f)
        if target != w["target_tss"]:
            w["target_tss"], w["target_hours"] = target, round(target / tph, 1)
            moved = True
    return moved


def project(plan: dict, today: date, load: dict, ctl_by_date: dict[str, float]) -> None:
    """
    ctl_end for every week, in place: the stored CTL at the end of a past week,
    and from today's load forward for the rest -- this week's remaining target
    over its remaining days, later weeks' targets spread evenly. The same daily
    recurrence as the stored series (_step).
    """
    c, a = load.get("ctl"), load.get("atl")
    started = c is not None and a is not None
    for w in plan["weeks"]:
        start = _ws(w)
        end = start + timedelta(days=6)
        if end < today:
            got = ctl_by_date.get(end.isoformat())
            if got is not None:
                w["ctl_end"] = round(got, 1)
            continue
        if not started:
            continue
        if start <= today:
            days = (end - today).days + 1
            remaining = max(w["target_tss"] - (w.get("actual_tss") or 0), 0)
        else:
            days, remaining = 7, w["target_tss"]
        for _ in range(days):
            c, a = _step(c, a, remaining / days)
        w["ctl_end"] = round(c, 1)


def _revision(
    now_iso: str, w: dict | None, field: str, frm, to, code: str, text: str, trigger: str = "sync"
) -> dict:
    return {
        "at": now_iso,
        "trigger": trigger,
        "week_start": w["week_start"] if w else None,
        "field": field,
        "from": frm,
        "to": to,
        "reason_code": code,
        "reason_text": text,
    }


def reconcile(
    plan: dict,
    today: date,
    totals: dict[str, dict],
    load: dict,
    last_workout: date | None,
    now_iso: str,
    ctl_by_date: dict[str, float] | None = None,
) -> tuple[dict, list[dict]]:
    """
    The plan as of this sync, and the revisions this run added (empty when
    nothing changed). `totals` is weekly TSS/hours keyed by week start (see
    service.weekly_totals), `load` today's combined {ctl, atl, tsb},
    `last_workout` the last day with any training.

    Actuals, last_form and ctl_end are refreshed on every run; only the target
    changes are revisions. Fitness plans get the refresh only for now.
    """
    plan = copy.deepcopy(plan)
    weeks = plan["weeks"]
    tsb = load.get("tsb")
    plan["last_form"] = {"ctl": load.get("ctl"), "atl": load.get("atl"), "tsb": tsb}

    for w in weeks:
        if _ws(w) <= today:
            split.set_actual(w, totals.get(w["week_start"]))

    added: list[dict] = []
    c = current_index(weeks, today)
    if plan.get("mode") == "event" and plan.get("status") == "active" and c is not None:
        added = _adapt(plan, today, c, tsb, last_workout, now_iso)

    project(plan, today, load, ctl_by_date or {})
    plan["revisions"] = (plan.get("revisions") or []) + added
    return plan, added


def _adapt(plan: dict, today: date, c: int, tsb: float | None, last_workout: date | None, now_iso: str) -> list[dict]:
    weeks = plan["weeks"]
    marks: list[str] = plan.setdefault("adapt_marks", [])
    before = snapshot(weeks)
    tss_per_hour = float((plan.get("baseline") or {}).get("tss_per_hour") or cfg.DEFAULT_TSS_PER_HOUR)
    cur = weeks[c]
    nxt = weeks[c + 1] if c + 1 < len(weeks) else None
    completed = weeks[:c]
    last_done = completed[-1] if completed else None
    # (week index, code, text) of the weeks a rule set directly.
    primary: list[tuple[int, str, str]] = []
    extra: list[dict] = []

    def fire(key: str) -> bool:
        if key in marks:
            return False
        marks.append(key)
        return True

    t = round(tsb) if tsb is not None else None
    fatigued = False

    # 1. Fatigue gate.
    if tsb is not None and tsb < cfg.GATE_RECOVERY_TSB:
        fatigued = True
    if fatigued and fire(f"FATIGUE_GATE_HIGH:{cur['week_start']}"):
        if _editable(cur):
            done = cur.get("actual_tss") or 0
            remaining = max(cur["target_tss"] - done, 0)
            _set(cur, "recovery", done + remaining * cfg.GATE_RECOVERY_FACTOR, tss_per_hour)
            primary.append((c, "FATIGUE_GATE", f"TSB {t}: the rest of this week halved, as a recovery week"))
        if nxt is not None and _editable(nxt):
            last, _ = _streak_before(weeks, c)
            base = last if last is not None else nxt["target_tss"]
            _set(nxt, "recovery", base * cfg.RECOVERY_FACTOR, tss_per_hour)
            primary.append((c + 1, "FATIGUE_GATE", f"TSB {t}: next week made a recovery week"))
        reflow(plan, c + 2, fixed=frozenset({c, c + 1}))
    elif not fatigued and tsb is not None and tsb < cfg.GATE_LOWER_TSB:
        # Below -40 the deeper gate above owns the week, whether or not it
        # already fired: the two never stack.
        fatigued = True
        target_i = next((i for i in range(c + 1, len(weeks)) if _editable(weeks[i]) and weeks[i]["kind"] == "loading"), None)
        if target_i is not None and fire(f"FATIGUE_GATE:{cur['week_start']}"):
            w = weeks[target_i]
            _set(w, "loading", w["target_tss"] * cfg.GATE_LOWER_FACTOR, tss_per_hour)
            primary.append((target_i, "FATIGUE_GATE", f"TSB {t}: week lowered 20%"))
            reflow(plan, target_i + 1, fixed=frozenset({target_i}))

    # 5 is checked before 2: an empty stretch is a layoff, never a reason to
    # rebase the whole path on it.
    days_off = None
    if last_workout is not None:
        created = date.fromisoformat((plan.get("created_at") or today.isoformat())[:10])
        days_off = (today - max(last_workout, created)).days
    layoff = days_off is not None and days_off >= cfg.LAYOFF_DAYS

    # 2. Under-delivery.
    loading_done = [w for w in completed if w["kind"] == "loading"]
    if not layoff and len(completed) >= 2 and completed[-1]["kind"] == "loading" and completed[-2]["kind"] == "loading":
        a, b = completed[-2], completed[-1]
        under = all(
            0 < (w.get("actual_tss") or 0) < w["target_tss"] * cfg.UNDER_DELIVERY_PCT for w in (a, b)
        )
        if under and _editable(cur) and fire(f"UNDER_DELIVERY:{b['week_start']}"):
            level = round(((a["actual_tss"] or 0) + (b["actual_tss"] or 0)) / 2)
            pct = [round(100 * w["actual_tss"] / w["target_tss"]) for w in (a, b)]
            reflow(plan, c, level=level)
            primary.append((c, "UNDER_DELIVERY", f"Last two weeks came in at {pct[0]}% and {pct[1]}% of target: rebuilt from {level} TSS"))
            targets = plan.get("targets") or {}
            top = max((w["target_tss"] for w in weeks[c:] if w["kind"] == "loading"), default=None)
            if top is not None and targets.get("peak_weekly_tss") and top < targets["peak_weekly_tss"]:
                extra.append(_revision(now_iso, None, "peak_weekly_tss", targets["peak_weekly_tss"], top, "PEAK_LOWERED", f"Peak lowered to {top} TSS a week"))
                targets["peak_weekly_tss"] = top
                # A taper sized off the old peak must not end up above the build.
                retaper(plan, today, only_if_above=True)

    # 3. Over-delivery hold.
    if (
        last_done is not None
        and tsb is not None
        and tsb < cfg.OVER_DELIVERY_TSB
        and (last_done.get("actual_tss") or 0) > last_done["target_tss"] * cfg.OVER_DELIVERY_PCT
        and _editable(cur)
        and cur["kind"] == "loading"
        and cur["target_tss"] > last_done["target_tss"]
        and fire(f"OVER_DELIVERY_HOLD:{last_done['week_start']}")
    ):
        pct = round(100 * last_done["actual_tss"] / last_done["target_tss"])
        _set(cur, "loading", last_done["target_tss"], tss_per_hour)
        primary.append((c, "OVER_DELIVERY_HOLD", f"Last week at {pct}% of target with TSB {t}: held at {round(last_done['target_tss'])} TSS"))
        reflow(plan, c + 1, fixed=frozenset({c}))

    # 4. Fresh bonus.
    if (
        not fatigued
        and last_done is not None
        and tsb is not None
        and tsb >= cfg.FRESH_BONUS_TSB
        and (last_done.get("actual_tss") or 0) >= last_done["target_tss"] * cfg.FRESH_BONUS_DONE_PCT
        and _editable(cur)
        and cur["kind"] == "loading"
        and fire(f"FRESH_BONUS:{last_done['week_start']}")
    ):
        prev, _ = _streak_before(weeks, c)
        raised = cur["target_tss"] * (1 + cfg.FRESH_BONUS_PCT)
        if prev is not None:
            raised = min(raised, prev * (1 + cfg.MAX_WEEKLY_GROWTH))
        if round(raised) > cur["target_tss"]:
            _set(cur, "loading", raised, tss_per_hour)
            primary.append((c, "FRESH_BONUS", f"Fresh (TSB +{t}) after a full week: raised up to 5%"))

    # 5. Layoff.
    if layoff and nxt is not None and _editable(nxt) and fire(f"LAYOFF_RETURN:{cur['week_start']}"):
        last = loading_done[-1]["target_tss"] if loading_done else nxt["target_tss"]
        _set(nxt, "return", last * cfg.RETURN_FACTOR, tss_per_hour)
        primary.append((c + 1, "LAYOFF_RETURN", f"{days_off} days without training: a return week at 60%"))
        reflow(plan, c + 2, fixed=frozenset({c + 1}))

    return diff_revisions(before, weeks, primary, now_iso, "sync") + extra


def snapshot(weeks: list[dict]) -> list[tuple[str, float]]:
    """Each week's (kind, target) before a change, for diff_revisions."""
    return [(w["kind"], w["target_tss"]) for w in weeks]


def diff_revisions(
    before: list[tuple[str, float]],
    weeks: list[dict],
    primary: list[tuple[int, str, str]],
    now_iso: str,
    trigger: str,
) -> list[dict]:
    """
    Revisions for a change: one per week set directly (`primary`: index, reason
    code, text) and one for the later weeks that re-flowed after it. A week
    that moved less than 1 TSS and kept its kind logs nothing.
    """
    added: list[dict] = []
    direct = {i: (code, text) for i, code, text in primary}
    flowed = []
    for i, (w, (kind0, tss0)) in enumerate(zip(weeks, before)):
        if abs(w["target_tss"] - tss0) < 1 and w["kind"] == kind0:
            continue
        if i in direct:
            code, text = direct[i]
            added.append(_revision(now_iso, w, "target_tss", tss0, w["target_tss"], code, text, trigger))
        else:
            flowed.append(i)
    if flowed:
        code = primary[0][1] if primary else "UNDER_DELIVERY"
        n = len(flowed)
        added.append(
            _revision(
                now_iso, weeks[flowed[0]], "later_weeks", None, None, code,
                f"{n} later week{'s' if n != 1 else ''} re-flowed to keep the 10% cap and recovery rhythm",
                trigger,
            )
        )
    return added
